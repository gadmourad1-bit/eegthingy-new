def _read_unique_regular(path: Path) -> bytes:
    absolute = Path(os.path.abspath(os.fspath(path)))
    before_path = absolute.lstat()
    if (
        stat.S_ISLNK(before_path.st_mode)
        or not stat.S_ISREG(before_path.st_mode)
        or before_path.st_nlink != 1
    ):
        raise RuntimeError(f"historical source is not a unique regular file: {path}")
    flags = os.O_RDONLY | getattr(os, "O_CLOEXEC", 0) | getattr(os, "O_NOFOLLOW", 0)
    descriptor = os.open(absolute, flags)
    try:
        before = os.fstat(descriptor)
        stable = (
            "st_dev",
            "st_ino",
            "st_mode",
            "st_nlink",
            "st_size",
            "st_mtime_ns",
            "st_ctime_ns",
        )
        if any(getattr(before, field) != getattr(before_path, field) for field in stable):
            raise RuntimeError(f"historical source changed while opening: {path}")
        chunks: list[bytes] = []
        while True:
            chunk = os.read(descriptor, 1024 * 1024)
            if not chunk:
                break
            chunks.append(chunk)
        after = os.fstat(descriptor)
        after_path = absolute.lstat()
        if any(
            getattr(before, field) != getattr(observed, field)
            for observed in (after, after_path)
            for field in stable
        ):
            raise RuntimeError(f"historical source changed during read: {path}")
        payload = b"".join(chunks)
        if len(payload) != before.st_size:
            raise RuntimeError(f"historical source read was incomplete: {path}")
        return payload
    finally:
        os.close(descriptor)


def archived_source_path(logical_name: str) -> Path:
    if logical_name not in PINNED_SOURCE_MANIFEST:
        raise RuntimeError(f"source is outside the frozen native-FBMS manifest: {logical_name}")
    relative = logical_name.removeprefix(LOGICAL_PACKAGE_PREFIX)
    if not relative or "/" in relative or relative in {".", ".."}:
        raise RuntimeError(f"unsafe frozen native-FBMS source key: {logical_name}")
    return ARCHIVE_ROOT / relative


def verify_archive() -> dict[str, str]:
    try:
        observed_names = {
            f"{LOGICAL_PACKAGE_PREFIX}{entry.name}"
            for entry in ARCHIVE_ROOT.iterdir()
        }
    except OSError as error:
        raise RuntimeError("frozen native-FBMS source archive is unavailable") from error
    if observed_names != set(PINNED_SOURCE_MANIFEST):
        raise RuntimeError("frozen native-FBMS source archive membership differs")
    observed: dict[str, str] = {}
    for name, expected in sorted(PINNED_SOURCE_MANIFEST.items()):
        actual = hashlib.sha256(_read_unique_regular(archived_source_path(name))).hexdigest()
        if actual != expected:
            raise RuntimeError(f"frozen native-FBMS source checksum differs: {name}")
        observed[name] = actual
    return observed


def validate_checkpoint_manifest(
    files: Mapping[str, object], required: Sequence[str]
) -> None:
    archive = verify_archive()
    missing = sorted(set(required) - set(files))
    if missing:
        raise RuntimeError(
            f"CardinalFBMS checkpoint source provenance is incomplete: {missing}"
        )
    for name in required:
        value = files[name]
        if not isinstance(value, str) or value != archive.get(name):
            raise RuntimeError(
                f"CardinalFBMS checkpoint differs from historical source: {name}"
            )


def logical_class_name(value: type[object]) -> str:
    return f"{value.__module__}.{value.__qualname__}"
